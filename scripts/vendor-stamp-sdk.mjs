// Write src/plugins/stamp-sdk-box.ts: the files of @botiverse/stamp-sdk that the run_js box loads, copied verbatim
// from the installed package at the version package.json pins (botiverse/antiproton#1092).
//
// Only the files `lib/client.mjs` imports, not the package entry: `index.mjs` pulls in the SDK's session handling
// (`injected-auth`, `session`), which holds and rotates a refresh token, and the box must hold no credential. The
// gateway does the refreshing (src/plugins/stamp.ts `bridgeSend`).
//
// Generated rather than hand-copied so the box runs the published artifact and nothing else; test/stamp-bridge.ts
// fails when the copy and node_modules differ, or the copy's version is not the pin. After changing the pin:
//
//   npm ci && node scripts/vendor-stamp-sdk.mjs
//
// `--check` writes nothing and exits 1 when the file on disk is not what this would write.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkgDir = join(root, "node_modules", "@botiverse", "stamp-sdk");
const FILES = ["lib/client.mjs", "lib/errors.mjs", "lib/locale.mjs"];
const OUT = join(root, "src", "plugins", "stamp-sdk-box.ts");

const installed = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8")).version;
const pinned = JSON.parse(readFileSync(join(root, "package.json"), "utf8")).dependencies["@botiverse/stamp-sdk"];
if (installed !== pinned) {
  console.error(`vendor-stamp-sdk: node_modules has ${installed}, package.json pins ${pinned}; run npm ci first`);
  process.exit(2);
}

const body = FILES.map((f) => `  ${JSON.stringify(f)}: ${JSON.stringify(readFileSync(join(pkgDir, f), "utf8"))},`).join("\n");
const text = `// Generated by scripts/vendor-stamp-sdk.mjs from @botiverse/stamp-sdk ${installed} — do not edit.
// The files the run_js box loads, verbatim; regenerate after changing the pin.

/** The version these files were copied from: package.json's pin of @botiverse/stamp-sdk. */
export const STAMP_SDK_VERSION = ${JSON.stringify(installed)};

/** \`lib/client.mjs\` of @botiverse/stamp-sdk ${installed} and what it imports, by their names in the package. */
export const FILES: Readonly<Record<string, string>> = {
${body}
};
`;

if (process.argv.includes("--check")) {
  let have = "";
  try { have = readFileSync(OUT, "utf8"); } catch { /* absent: differs */ }
  if (have !== text) {
    console.error(`vendor-stamp-sdk: ${OUT} is not what node_modules (${installed}) gives; run node scripts/vendor-stamp-sdk.mjs`);
    process.exit(1);
  }
  console.log(`vendor-stamp-sdk: up to date (${installed})`);
} else {
  writeFileSync(OUT, text);
  console.log(`vendor-stamp-sdk: wrote ${OUT} (${installed}, ${FILES.length} files)`);
}
